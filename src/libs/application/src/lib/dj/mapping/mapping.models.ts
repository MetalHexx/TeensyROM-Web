import type { MappingStyleKind } from '../ports';
import type { Slot } from '../slot';

export const VOICE_NUMBERS = [1, 2, 3] as const;

/** The panel controls each voice strip repeats, named as the strip's own `data-control`. */
export const VOICE_STRIP_CONTROLS = [
  'wave-triangle',
  'wave-sawtooth',
  'wave-pulse',
  'wave-noise',
  'coarse',
  'fine',
  'pulse-width',
  'attack',
  'decay',
  'sustain',
  'release',
  'ring',
  'sync',
  'filter',
] as const;

/** The panel controls each deck has once. */
export const DECK_PANEL_CONTROLS = [
  'filter-cutoff',
  'filter-resonance',
  'filter-low-pass',
  'filter-band-pass',
  'filter-high-pass',
  'panic',
] as const;

type VoiceNumber = (typeof VOICE_NUMBERS)[number];

export type VoiceStripControl = (typeof VOICE_STRIP_CONTROLS)[number];

export type DeckControlId =
  | 'play-pause'
  | 'stop'
  | 'subtune-previous'
  | 'subtune-next'
  | 'seek'
  | 'speed'
  | 'speed-jump-up'
  | 'speed-jump-home'
  | 'speed-jump-down'
  | 'speed-nudge-up'
  | 'speed-nudge-down'
  | 'repeat'
  | `voice-${VoiceNumber}-mute`
  | `voice-${VoiceNumber}-hold`
  | 'key'
  | `voice-${VoiceNumber}-${VoiceStripControl}`
  | (typeof DECK_PANEL_CONTROLS)[number];

/** Every deck control a MIDI source can drive, in display order. The server's allow-list is
 *  loaded from a contract file generated from this list, so the two cannot drift.
 *
 *  Adding a control: add it to the pattern above (or to the transport and voice entries), give it a
 *  `MappableControls` entry and its `data-control` attribute on the element. The overlay anchors
 *  derive from the list, and the contract file is regenerated by the `application` test run
 *  (`pnpm nx test application -- -u`) and committed. */
export const DECK_CONTROL_IDS: readonly DeckControlId[] = [
  'play-pause',
  'stop',
  'subtune-previous',
  'subtune-next',
  'seek',
  'speed',
  'speed-jump-up',
  'speed-jump-home',
  'speed-jump-down',
  'speed-nudge-up',
  'speed-nudge-down',
  'repeat',
  ...VOICE_NUMBERS.map((n) => `voice-${n}-mute` as const),
  ...VOICE_NUMBERS.map((n) => `voice-${n}-hold` as const),
  'key',
  ...VOICE_NUMBERS.flatMap((n) =>
    VOICE_STRIP_CONTROLS.map((control) => `voice-${n}-${control}` as const)
  ),
  ...DECK_PANEL_CONTROLS,
];

export type ControlId = DeckControlId;

/** Who a control belongs to. A later surface (a playlist) adds one member here; the mixer owns
 *  nothing today. */
export type ControlOwner = Slot | 'mixer';

export interface ControlIdentity {
  readonly owner: ControlOwner;
  readonly control: ControlId;
}

/** How a control behaves: a trigger fires, a state is on or off, a value has a range, and a hold
 *  is on only while its key is down. */
export type ControlNature = 'trigger' | 'state' | 'value' | 'hold';

export type MidiSourceKind = 'note' | 'cc';

export interface MidiSource {
  readonly controllerId: string;
  /** 1–16. */
  readonly channel: number;
  readonly kind: MidiSourceKind;
  /** 0–127: the note number or the controller number. */
  readonly number: number;
}

export interface MappingStyle {
  readonly kind: MappingStyleKind;
  /** A fraction of the control's range; `null` for every kind that takes none. */
  readonly amount: number | null;
}

export interface ControlMapping {
  readonly id: string;
  readonly source: MidiSource;
  readonly control: ControlIdentity;
  readonly style: MappingStyle;
}

export interface KnownController {
  readonly id: string;
  readonly name: string;
  readonly lastPortId: string | null;
  readonly listening: boolean;
}

/** One decoded message from a source: `value` is 0–127 and `pressed` is its key edge state. */
export interface SourceEvent extends MidiSource {
  readonly value: number;
  readonly pressed: boolean;
}

const CONTROL_IDS: ReadonlySet<string> = new Set<string>(DECK_CONTROL_IDS);

export function isControlId(value: string): value is ControlId {
  return CONTROL_IDS.has(value);
}

/** The identity of a control, unique across owners. */
export function controlKey(identity: ControlIdentity): string {
  return `${identity.owner}:${identity.control}`;
}

/** The identity of a source, unique across controllers. */
export function sourceKey(source: MidiSource): string {
  return `${source.controllerId}|${source.channel}|${source.kind}|${source.number}`;
}
